export function CapabilityIcon({
  kind,
  id,
  compact = false,
}: {
  kind: CapabilityKind;
  id?: string;
  compact?: boolean;
}) {
  const specs = kind === 'skill' ? skillIconSpecs : mcpIconSpecs;
  const spec = id ? specs[id] : undefined;
  const MainIcon = spec?.icon ?? (kind === 'skill' ? Blocks : ServerCog);
  const FeatureIcon = spec?.feature;

  return (
    <span
      className={`capability-icon-tile icon-tone-${spec?.tone ?? 'neutral'} ${
        compact ? 'is-compact' : ''
      }`}
      aria-hidden="true"
    >
      {spec?.brand ? (
        <BrandGlyph name={spec.brand} />
      ) : (
        <MainIcon className="capability-main-icon" />
      )}
      {FeatureIcon ? (
        <span className="capability-icon-badge">
          <FeatureIcon />
        </span>
      ) : null}
    </span>
  );
}

export function hasCapabilityIcon(kind: CapabilityKind, id: string): boolean {
  return Boolean(kind === 'skill' ? skillIconSpecs[id] : mcpIconSpecs[id]);
}

function BrandGlyph({ name }: { name: BrandIconName }) {
  return (
    <svg
      className="capability-brand-icon"
      viewBox="0 0 24 24"
      focusable="false"
    >
      <path d={brandPaths[name]} />
    </svg>
  );
}
